let currentLang = localStorage.getItem('sp_lang') || (typeof navigator !== 'undefined' && navigator.language && navigator.language.startsWith('fr') ? 'fr' : 'en');
if (currentLang !== 'en' && currentLang !== 'fr') currentLang = 'en';

function refreshIcons() {
    if (typeof window !== 'undefined' && window.lucide && typeof window.lucide.createIcons === 'function') {
        try { window.lucide.createIcons(); } catch (_) {}
    }
}

function t(key, fallback = '') {
    const dict = translations[currentLang] || translations.en;
    return dict[key] || translations.en[key] || fallback || key;
}

function setLang(lang) {
    currentLang = (lang === 'fr') ? 'fr' : 'en';
    localStorage.setItem('sp_lang', currentLang);
    document.documentElement.lang = currentLang;

    const btnEn = document.getElementById('btn-lang-en');
    const btnFr = document.getElementById('btn-lang-fr');
    if (btnEn) btnEn.classList.toggle('active', currentLang === 'en');
    if (btnFr) btnFr.classList.toggle('active', currentLang === 'fr');

    const txtPanel = document.getElementById('txt-tab-panel');
    const txtCanvas = document.getElementById('txt-tab-canvas');
    if (txtPanel) txtPanel.innerText = (currentLang === 'fr') ? 'Palette & Réglages' : 'Palette & Tools';
    if (txtCanvas) txtCanvas.innerText = (currentLang === 'fr') ? 'Vue 3D & Peinture' : '3D Paint Canvas';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.innerText = translations[currentLang][key];
        }
    });

    document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
        const key = el.getAttribute('data-i18n-tooltip');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.setAttribute('data-tooltip', translations[currentLang][key]);
        }
    });

    document.querySelectorAll('[data-i18n-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-label');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.label = translations[currentLang][key];
        }
    });

    if (typeof updateHUDLabels === 'function') updateHUDLabels();
    refreshIcons();
    if (window.innerWidth <= 900 && typeof setMobileView === 'function') {
        setMobileView('canvas');
    }
    if (typeof updateMobileFilamentBar === 'function') updateMobileFilamentBar();
}
